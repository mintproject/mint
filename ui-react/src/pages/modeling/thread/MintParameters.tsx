/**
 * MintParameters — parameter sweep configuration for the execution pipeline.
 *
 * 1:1 port of the legacy LitElement MintParameters component.
 * Lets the domain scientist specify values for adjustable model parameters,
 * supporting comma-separated multi-value sweeps to generate ensemble runs.
 *
 * Legacy: ui/src/screens/modeling/thread/mint-parameters.ts
 */
import { ChevronDown, Edit2 } from 'lucide-react';
import { useRef, useState } from 'react';

import {
  ExecutionSummaryMap,
  ModelEnsembleMap,
  ModelParameter,
  ThreadExecutionData,
} from '@/graphql/generated/execution';
import { parametersComplete, totalConfigs } from '@/lib/thread-execution';
import {
  SECRET_READINESS_HELP,
  SECRET_READINESS_LABEL,
  hasSecretParameters,
  userParameters,
} from '@/lib/secret-parameters';
import {
  adapterParameterKey,
  adapterPlanIsTransformRequired,
  adapterPlanParameters,
  adapterValueText,
  type ThreadAdapterPlan,
} from '@/lib/adapter-execution';
import type { UnifiedParameterDefinition } from '@/lib/ensemble-manager';
import type { SpatialSelection } from './SpatialScopeMap';

// ─── Constants ─────────────────────────────────────────────────────────────────

const MAX_PARAMETER_COMBINATIONS = 100000;

// These values are generated by the spatial layer/feature picker above. Keep
// their inputs in the form for adapter-plan submission, but do not duplicate
// them as manual fields in the visible parameter table.
const MAP_GENERATED_ADAPTER_PARAMETERS = new Set([
  'geometry_source_uri',
  'geometry_source_type',
  'geometry_layer',
  'geometry_id_field',
  'geometry_name_field',
  'geometry_filter_field',
  'geometry_filter_value',
  'geometry_crs',
  'geometry_format',
  'crs_requirement',
  'format',
  'spatial_scope_type',
  'spatial_scope_id',
  'spatial_scope_name',
  'spatial_resolution',
]);

// ─── Helpers ───────────────────────────────────────────────────────────────────

function formatDate(ts: number): string {
  const date = new Date(ts);
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  const year = date.getFullYear();
  return `${month}/${day}/${year}`;
}

function spatialParameterOverride(
  name: string,
  selection: SpatialSelection | null | undefined,
  scopeId?: string | null,
  scopeName?: string | null,
): string | undefined {
  const layer = selection?.layer;
  const feature = selection?.feature;
  switch (name) {
    case 'geometry_source_uri':
      return layer?.uri;
    case 'geometry_source_type':
      return layer?.geometry_type;
    case 'geometry_filter_field':
      return feature?.filterField ?? layer?.default_filter_field;
    case 'geometry_filter_value':
      return feature?.filterValue;
    case 'geometry_crs':
    case 'crs_requirement':
      return layer?.crs;
    case 'geometry_format':
    case 'format':
      return layer?.format;
    case 'spatial_scope_type':
      return layer?.tags?.includes('gma') ? 'gma' : undefined;
    case 'spatial_scope_id':
      return feature?.filterValue ?? scopeId ?? undefined;
    case 'spatial_scope_name':
      return feature?.label ?? scopeName ?? undefined;
    case 'spatial_resolution':
      return layer?.geometry_type === 'polygon' ? 'polygon' : undefined;
    default:
      return undefined;
  }
}

// ─── Props ────────────────────────────────────────────────────────────────────

interface MintParametersProps {
  threadData: ThreadExecutionData;
  canWrite: boolean;
  canExecute: boolean;
  problemStartDate?: number | null;
  problemEndDate?: number | null;
  onSave: (
    modelEnsembles: ModelEnsembleMap,
    executionSummary: ExecutionSummaryMap,
    notes: string,
    adapterPlans: ThreadAdapterPlan[],
  ) => Promise<void>;
  onContinue: () => void;
  adapterPlanError?: string | null;
  adapterPlanLoading?: boolean;
  spatialScopeName?: string | null;
  spatialScopeId?: string | null;
  spatialSelection?: SpatialSelection | null;
}

// ─── Component ────────────────────────────────────────────────────────────────

export function MintParameters({
  threadData,
  canWrite,
  problemStartDate,
  problemEndDate,
  onSave,
  onContinue,
  adapterPlanError,
  adapterPlanLoading = false,
  spatialScopeName,
  spatialScopeId,
  spatialSelection,
}: MintParametersProps) {
  const modelIds = Object.keys(threadData.models ?? {});
  const isConfigured = modelIds.length > 0;

  // Shared with the wizard rail. Note it also requires an execution summary: a
  // model with no adjustable parameters would otherwise read as done before the
  // step had written anything, and the Runs step would have nothing to submit.
  const isDone = parametersComplete(threadData);

  const [editMode, setEditMode] = useState(!isDone);
  const [waiting, setWaiting] = useState(false);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const formRefs = useRef<Record<string, HTMLFormElement | null>>({});
  const notesRef = useRef<HTMLTextAreaElement>(null);

  // ─ Validate a single input value ──────────────────────────────────────────
  function validateValues(param: ModelParameter, values: string[]): string | null {
    for (const v of values) {
      if (!v) continue;
      if (param.type === 'string' && param.accepted_values) {
        if (!param.accepted_values.includes(v)) {
          return `Accepted values: ${param.accepted_values.join(', ')}`;
        }
      } else if (param.type === 'int') {
        const n = parseInt(v, 10);
        if (param.min != null && n < parseInt(param.min, 10)) return `Min is ${param.min}`;
        if (param.max != null && n > parseInt(param.max, 10)) return `Max is ${param.max}`;
      } else if (param.type === 'float') {
        const n = parseFloat(v);
        if (param.min != null && n < parseFloat(param.min)) return `Min is ${param.min}`;
        if (param.max != null && n > parseFloat(param.max)) return `Max is ${param.max}`;
      }
    }
    return null;
  }

  // ─ Parse values from the form for a parameter ─────────────────────────────
  function getParamValues(modelId: string, param: ModelParameter): string[] {
    const form = formRefs.current[modelId];
    if (!form) return [];
    const el = form.elements.namedItem(param.id ?? '') as HTMLInputElement | null;
    const raw = el?.value ?? param.default ?? '';
    return raw
      .split(/\s*,\s*/)
      .map((s) => s.trim())
      .filter(Boolean);
  }

  function getAdapterParamValues(modelId: string, name: string, fallback: unknown): string[] {
    const form = formRefs.current[modelId];
    const fieldName = adapterParameterKey(modelId, name);
    const el =
      (form?.elements.namedItem(fieldName) as HTMLInputElement | null) ??
      Array.from(document.querySelectorAll<HTMLInputElement>('input')).find(
        (input) => input.name === fieldName,
      );
    const raw = el?.value ?? adapterValueText(fallback);
    return raw.trim() ? [raw.trim()] : [];
  }

  function validateAdapterValue(
    parameter: {
      type?: string;
      allowed_values?: unknown[];
      minimum?: number;
      maximum?: number;
    },
    value: string,
  ): string | null {
    if (
      parameter.allowed_values?.length &&
      !parameter.allowed_values.some((item) => String(item) === value)
    ) {
      return `Accepted values: ${parameter.allowed_values.join(', ')}`;
    }
    if (parameter.type && ['integer', 'int', 'number', 'float'].includes(parameter.type)) {
      const numberValue = Number(value);
      if (!Number.isFinite(numberValue)) return 'Enter a number';
      if (parameter.minimum != null && numberValue < parameter.minimum) {
        return `Min is ${parameter.minimum}`;
      }
      if (parameter.maximum != null && numberValue > parameter.maximum) {
        return `Max is ${parameter.maximum}`;
      }
    }
    return null;
  }

  function adapterValueForStorage(parameter: { type?: string }, value: string): unknown {
    if (parameter.type === 'boolean' || parameter.type === 'bool') return value === 'true';
    if (parameter.type === 'integer' || parameter.type === 'int') return Number.parseInt(value, 10);
    if (parameter.type === 'number' || parameter.type === 'float') return Number(value);
    return value;
  }

  // ─ Save handler ───────────────────────────────────────────────────────────
  async function handleSave() {
    const newErrors: Record<string, string> = {};
    const newEnsembles: ModelEnsembleMap = {
      ...Object.fromEntries(
        Object.entries(threadData.model_ensembles).map(([k, v]) => [
          k,
          { ...v, bindings: { ...v.bindings } },
        ]),
      ),
    };
    const newSummary: ExecutionSummaryMap = {};
    const newAdapterPlans: ThreadAdapterPlan[] = [];
    let allOk = true;

    for (const mid of modelIds) {
      const model = threadData.models[mid]!;
      const adjustable = userParameters(model).filter((p) => !p.value);
      const bindings = newEnsembles[mid]?.bindings ?? {};
      const adapterPlans = threadData.adapter_plans?.[mid] ?? [];
      const adapterParameters = new Map<string, UnifiedParameterDefinition>();
      for (const plan of adapterPlans) {
        if (!adapterPlanIsTransformRequired(plan)) continue;
        for (const parameter of adapterPlanParameters(plan)) {
          if (parameter.managed) continue;
          if (!adapterParameters.has(parameter.name))
            adapterParameters.set(parameter.name, parameter);
        }
      }
      const existingAdapterValues: Record<string, unknown> = {};
      for (const parameter of adapterParameters.values()) {
        const existing = adapterPlans.find(
          (plan) => plan.parameter_values?.[parameter.name] !== undefined,
        );
        if (existing)
          existingAdapterValues[parameter.name] = existing.parameter_values[parameter.name];
      }

      const nextAdapterValues = { ...existingAdapterValues };
      for (const parameter of adapterParameters.values()) {
        const current = nextAdapterValues[parameter.name];
        if (!editMode && current !== undefined && adapterValueText(current).trim()) continue;
        const values = getAdapterParamValues(mid, parameter.name, current);
        const value = values[0];
        if (value === undefined) {
          delete nextAdapterValues[parameter.name];
          continue;
        }
        const error = validateAdapterValue(parameter, value);
        if (error) {
          newErrors[`${mid}::adapter::${parameter.name}`] = error;
          allOk = false;
        } else {
          nextAdapterValues[parameter.name] = adapterValueForStorage(parameter, value);
        }
      }

      for (const plan of adapterPlans) {
        const names = new Set(adapterPlanParameters(plan).map((parameter) => parameter.name));
        newAdapterPlans.push({
          ...plan,
          parameter_values: Object.fromEntries(
            Object.entries({ ...plan.parameter_values, ...nextAdapterValues }).filter(([name]) =>
              names.has(name),
            ),
          ),
        });
      }

      for (const param of adjustable) {
        const current = bindings[param.id ?? ''];
        // If not in edit mode and already bound, keep existing
        if (!editMode && current && current.length > 0) continue;

        const vals = getParamValues(mid, param);
        const err = validateValues(param, vals);
        if (err) {
          newErrors[`${mid}::${param.id}`] = err;
          allOk = false;
        } else {
          if (!newEnsembles[mid]) {
            newEnsembles[mid] = { id: threadData.model_ensembles[mid]?.id ?? '', bindings: {} };
          }
          newEnsembles[mid]!.bindings[param.id ?? ''] = vals;
        }
      }

      const cfg = totalConfigs(model, newEnsembles[mid]?.bindings ?? {}, threadData.data);
      if (cfg > MAX_PARAMETER_COMBINATIONS) {
        alert(
          `Too many parameter combinations (${cfg}) for the model '${model.name}'. Please reduce the number of values.`,
        );
        allOk = false;
      }

      newSummary[mid] = {
        total_runs: cfg,
        submitted_runs: 0,
        failed_runs: 0,
        successful_runs: 0,
      };
    }

    setErrors(newErrors);
    if (!allOk) return;

    setWaiting(true);
    try {
      await onSave(newEnsembles, newSummary, notesRef.current?.value ?? '', newAdapterPlans);
      setEditMode(false);
    } finally {
      setWaiting(false);
    }
  }

  // ─ Get default value for a param (handles region_geojson, dates) ──────────
  function getDefaultDisplayValue(param: ModelParameter): string {
    if (param.default === '__region_geojson') return 'Region GeoJSON';
    if (param.type?.includes('StartDate') && problemStartDate) return formatDate(problemStartDate);
    if (param.type?.includes('EndDate') && problemEndDate) return formatDate(problemEndDate);
    return param.default ?? '';
  }

  // ─ No models guard ────────────────────────────────────────────────────────
  if (!isConfigured) {
    return (
      <div data-testid="mint-parameters">
        <p className="mb-2 text-sm text-gray-600">
          Please specify the values for the adjustable parameters.
        </p>
        <p className="text-sm text-gray-500">Please select model(s) first.</p>
      </div>
    );
  }

  // ─ Latest events ──────────────────────────────────────────────────────────

  return (
    <div data-testid="mint-parameters">
      <p className="mb-4 text-sm text-gray-600">
        This step is for specifying values for the adjustable parameters of the models that you
        selected earlier.
      </p>

      {adapterPlanError && (
        <p
          className="mb-4 rounded border border-red-200 bg-red-50 p-2 text-sm text-red-700"
          role="alert"
        >
          Unable to discover the SVO adapter plan: {adapterPlanError}
        </p>
      )}

      {adapterPlanLoading && (
        <p className="mb-4 rounded border border-blue-200 bg-blue-50 p-2 text-sm text-blue-700">
          Discovering SVO adapter requirements for the selected resources…
        </p>
      )}

      {isDone && canWrite && !editMode && (
        <p className="mb-4 text-sm text-gray-500">
          Please click on the <span className="font-mono">✎</span> icon to make changes and run the
          model.
        </p>
      )}

      {/* ── Setup Models ── */}
      <div className="mb-4 rounded-md border">
        <div className="flex items-center justify-between rounded-t-md border-b bg-gray-50 px-4 py-2">
          <h3 className="text-sm font-semibold">Setup Models</h3>
          {canWrite && !editMode && (
            <button
              type="button"
              aria-label="Edit parameters"
              data-testid="edit-parameters-btn"
              onClick={() => setEditMode(true)}
              className="rounded p-1 text-gray-500 hover:bg-gray-200"
            >
              <Edit2 className="h-4 w-4" />
            </button>
          )}
        </div>

        <ul className="divide-y">
          {modelIds.map((mid) => {
            const model = threadData.models[mid]!;
            const ensemble = threadData.model_ensembles[mid] ?? { id: '', bindings: {} };

            const fixedParams = userParameters(model)
              .filter((p) => !!p.value)
              .sort((a, b) => {
                if (a.position != null && b.position != null) return a.position - b.position;
                return (a.name ?? '').localeCompare(b.name ?? '');
              });

            const adjustableParams = userParameters(model)
              .filter((p) => !p.value)
              .sort((a, b) => {
                if (a.position != null && b.position != null) return a.position - b.position;
                return (a.name ?? '').localeCompare(b.name ?? '');
              });

            const adapterPlans = threadData.adapter_plans?.[mid] ?? [];
            const adapterParams = new Map<
              string,
              ReturnType<typeof adapterPlanParameters>[number]
            >();
            for (const plan of adapterPlans) {
              if (!adapterPlanIsTransformRequired(plan)) continue;
              for (const parameter of adapterPlanParameters(plan)) {
                if (parameter.managed) continue;
                if (!adapterParams.has(parameter.name))
                  adapterParams.set(parameter.name, parameter);
              }
            }

            return (
              <li key={mid} className="px-4 py-3">
                <h4 className="mb-2 text-sm font-medium">
                  Model: <span className="text-blue-700">{model.name}</span>
                </h4>
                {hasSecretParameters(model) && (
                  <p
                    className="mb-2 text-xs text-gray-600"
                    data-testid={`secret-readiness-${mid}`}
                    title={SECRET_READINESS_HELP}
                  >
                    {SECRET_READINESS_LABEL}
                    <span className="sr-only">. {SECRET_READINESS_HELP}</span>
                  </p>
                )}
                <ul className="space-y-3">
                  {/* Fixed (expert-set) parameters */}
                  {fixedParams.length > 0 && (
                    <li>
                      <p className="mb-1 text-xs font-semibold">
                        Expert modeler has selected the following parameters:
                      </p>
                      <table className="w-full border-collapse text-xs">
                        <thead>
                          <tr className="bg-gray-100">
                            <th className="w-3/5 px-2 py-1 text-left font-semibold">
                              Adjustable Parameter
                            </th>
                            <th className="px-2 py-1 text-left font-semibold">Values</th>
                          </tr>
                        </thead>
                        <tbody>
                          {fixedParams.map((p) => (
                            <tr key={p.id} className="odd:bg-white even:bg-gray-50">
                              <td className="px-2 py-1">
                                <div className="font-medium">
                                  {(p.name ?? '').replace(/_/g, ' ')}
                                </div>
                                {p.description && (
                                  <div className="text-gray-500">{p.description}</div>
                                )}
                              </td>
                              <td className="px-2 py-1">
                                {p.default === '__region_geojson' ? 'Region GeoJSON' : p.value}
                              </td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </li>
                  )}

                  {/* Adjustable parameters */}
                  {adjustableParams.length > 0 ? (
                    <li>
                      {editMode && (
                        <p className="mb-1 text-xs text-gray-600">
                          Setup the model by specifying values below. You can enter more than one
                          value (comma separated) if you want several runs.
                        </p>
                      )}
                      {model.usage_notes && (
                        <p className="mb-1 text-xs text-gray-500">{model.usage_notes}</p>
                      )}
                      <form
                        ref={(el) => {
                          formRefs.current[mid] = el;
                        }}
                        data-testid={`param-form-${mid}`}
                      >
                        <table className="w-full border-collapse text-xs">
                          <thead>
                            <tr className="bg-gray-100">
                              <th className="w-3/5 px-2 py-1 text-left font-semibold">
                                Adjustable Parameter
                              </th>
                              <th className="px-2 py-1 text-left font-semibold">Values</th>
                            </tr>
                          </thead>
                          <tbody>
                            {adjustableParams.map((p) => {
                              const bindings = ensemble.bindings[p.id ?? ''] ?? [];
                              const displayValue = bindings.join(', ');
                              const isRegionGeoJson = p.default === '__region_geojson';
                              const errKey = `${mid}::${p.id}`;

                              return (
                                <tr key={p.id} className="odd:bg-white even:bg-gray-50">
                                  <td className="px-2 py-1">
                                    <div className="font-medium">
                                      {(p.name ?? '').replace(/_/g, ' ')}
                                    </div>
                                    {p.description && (
                                      <div className="text-gray-500">{p.description}</div>
                                    )}
                                    {(p.min != null || p.max != null) && (
                                      <div className="text-gray-400">
                                        {p.min != null && p.max != null
                                          ? `Range: ${p.min} – ${p.max}.`
                                          : p.min != null
                                            ? `Min: ${p.min}.`
                                            : `Max: ${p.max}.`}
                                        {p.default && ` Default: ${p.default}`}
                                      </div>
                                    )}
                                  </td>
                                  <td className="px-2 py-1">
                                    {!editMode ? (
                                      <span>{displayValue || '—'}</span>
                                    ) : isRegionGeoJson ? (
                                      <span className="text-gray-500">Region GeoJSON</span>
                                    ) : (
                                      <div>
                                        <input
                                          type="text"
                                          name={p.id ?? ''}
                                          data-testid={`param-input-${p.id}`}
                                          defaultValue={displayValue}
                                          placeholder={getDefaultDisplayValue(p)}
                                          className="w-full rounded border px-2 py-1 text-xs focus:outline-none focus:ring-1 focus:ring-blue-400"
                                        />
                                        {errors[errKey] && (
                                          <div
                                            className="mt-0.5 text-xs text-red-500"
                                            data-testid={`param-error-${p.id}`}
                                          >
                                            {errors[errKey]}
                                          </div>
                                        )}
                                      </div>
                                    )}
                                  </td>
                                </tr>
                              );
                            })}
                          </tbody>
                        </table>
                      </form>
                    </li>
                  ) : (
                    <li>
                      <p className="text-xs font-semibold text-gray-500">
                        There are no adjustments possible for this model.
                      </p>
                    </li>
                  )}
                  {adapterParams.size > 0 && (
                    <li>
                      <p className="mb-1 text-xs font-semibold">SVO adapter parameters</p>
                      <p className="mb-1 text-xs text-gray-600">
                        These values configure the inferred conversion for the selected input. They
                        are saved with the adapter plan and are required before submission.
                      </p>
                      <table
                        className={`w-full border-collapse text-xs ${
                          [...adapterParams.values()].every((parameter) =>
                            MAP_GENERATED_ADAPTER_PARAMETERS.has(parameter.name),
                          )
                            ? 'hidden'
                            : ''
                        }`}
                      >
                        <thead>
                          <tr className="bg-gray-100">
                            <th className="w-3/5 px-2 py-1 text-left font-semibold">
                              Adapter parameter
                            </th>
                            <th className="px-2 py-1 text-left font-semibold">Value</th>
                          </tr>
                        </thead>
                        <tbody>
                          {[...adapterParams.values()].map((parameter) => {
                            const existingPlan = adapterPlans.find(
                              (plan) => plan.parameter_values?.[parameter.name] !== undefined,
                            );
                            const displayValue =
                              spatialParameterOverride(
                                parameter.name,
                                spatialSelection,
                                spatialScopeId,
                                spatialScopeName,
                              ) ??
                              (existingPlan
                                ? adapterValueText(existingPlan.parameter_values[parameter.name])
                                : adapterValueText(parameter.default));
                            const errKey = `${mid}::adapter::${parameter.name}`;
                            const mapGenerated = MAP_GENERATED_ADAPTER_PARAMETERS.has(
                              parameter.name,
                            );
                            return (
                              <tr
                                key={parameter.name}
                                hidden={mapGenerated}
                                className="odd:bg-white even:bg-gray-50"
                              >
                                <td className="px-2 py-1">
                                  <div className="font-medium">
                                    {parameter.name.replace(/_/g, ' ')}
                                    {parameter.required ? ' *' : ''}
                                  </div>
                                  {parameter.description && (
                                    <div className="text-gray-500">{parameter.description}</div>
                                  )}
                                  {parameter.source_transform && (
                                    <div className="text-gray-400">
                                      Transform: {parameter.source_transform}
                                    </div>
                                  )}
                                  {(parameter.minimum != null || parameter.maximum != null) && (
                                    <div className="text-gray-400">
                                      {parameter.minimum != null && parameter.maximum != null
                                        ? `Range: ${parameter.minimum} – ${parameter.maximum}`
                                        : parameter.minimum != null
                                          ? `Min: ${parameter.minimum}`
                                          : `Max: ${parameter.maximum}`}
                                    </div>
                                  )}
                                </td>
                                <td className="px-2 py-1">
                                  {!editMode ? (
                                    <span>{displayValue || '—'}</span>
                                  ) : (
                                    <div>
                                      <input
                                        type="text"
                                        name={adapterParameterKey(mid, parameter.name)}
                                        data-testid={`adapter-param-input-${parameter.name}`}
                                        defaultValue={displayValue}
                                        placeholder={
                                          parameter.default == null
                                            ? ''
                                            : adapterValueText(parameter.default)
                                        }
                                        className="w-full rounded border px-2 py-1 text-xs focus:outline-none focus:ring-1 focus:ring-blue-400"
                                      />
                                      {errors[errKey] && (
                                        <div
                                          className="mt-0.5 text-xs text-red-500"
                                          data-testid={`adapter-param-error-${parameter.name}`}
                                        >
                                          {errors[errKey]}
                                        </div>
                                      )}
                                    </div>
                                  )}
                                </td>
                              </tr>
                            );
                          })}
                        </tbody>
                      </table>
                    </li>
                  )}
                </ul>
              </li>
            );
          })}
        </ul>
      </div>

      {/* ── Footer ── */}
      {canWrite && (!isDone || editMode) ? (
        <div className="mt-4 space-y-3">
          <div className="flex justify-end gap-2">
            {editMode && (
              <button
                type="button"
                onClick={() => setEditMode(false)}
                disabled={waiting}
                className="rounded border border-gray-300 px-4 py-2 text-sm hover:bg-gray-50 disabled:opacity-50"
              >
                Cancel
              </button>
            )}
            <button
              type="button"
              data-testid="parameters-save-btn"
              onClick={() => void handleSave()}
              disabled={waiting || adapterPlanLoading}
              className="rounded bg-blue-600 px-4 py-2 text-sm text-white hover:bg-blue-700 disabled:opacity-50"
            >
              {waiting ? (
                <>
                  Saving…{' '}
                  <span className="inline-block h-3 w-3 animate-spin rounded-full border-2 border-white border-t-transparent" />
                </>
              ) : (
                'Select & Continue'
              )}
            </button>
          </div>
          <div>
            <label className="mb-1 block text-xs font-semibold text-gray-500">Notes</label>
            <textarea
              ref={notesRef}
              className="w-full rounded border px-2 py-1 text-sm focus:outline-none focus:ring-1 focus:ring-blue-400"
              rows={3}
              data-testid="parameters-notes"
            />
          </div>
        </div>
      ) : (
        <div className="mt-4 flex justify-end">
          <button
            type="button"
            data-testid="parameters-continue-btn"
            onClick={onContinue}
            className="rounded bg-blue-600 px-4 py-2 text-sm text-white hover:bg-blue-700"
          >
            Continue
            <ChevronDown className="ml-1 inline h-4 w-4 -rotate-90" />
          </button>
        </div>
      )}
    </div>
  );
}
